// Слой "core" — единая точка логирования значимых асинхронных шагов
// (загрузка данных, инициализация карты). Смысл не в самой обёртке
// console.* (её и так можно вызвать где угодно), а в том, что успех и
// провал шага логируются ИЗ ОДНОГО МЕСТА — нельзя написать fetch без лога,
// не переписав саму loggedStep(). Раньше в app/main.ts начало и успех
// загрузки detail-файлов не логировались вовсе (только провал через
// отдельный console.error на каждый из трёх), из-за чего "тихо ничего не
// произошло" (например, сеть подвисла) было неотличимо в консоли от
// "всё ещё грузится".

/**
 * Оборачивает один асинхронный шаг логированием начала/успеха/провала.
 * Ошибка пробрасывается дальше как есть (`throw error`) — вызывающий код
 * сам решает, что делать дальше (показать баннер, оставить индикатор
 * загрузки навсегда, как в `app/main.ts` для detail-файлов `--public`
 * сборки) — loggedStep только гарантирует, что провал в любом случае
 * виден в консоли, а не только там, где кто-то не забыл про try/catch.
 *
 * @typeParam T - тип результата шага.
 * @param name - имя шага для логов (например, "graph-data.json").
 * @param action - сам асинхронный шаг.
 * @returns Результат `action()`.
 * @throws То же, что бросит `action()` — после того, как ошибка залогирована.
 *
 * @example
 * const data = await loggedStep("graph-data.json", () => loadGraphData(url));
 */
export async function loggedStep<T>(name: string, action: () => Promise<T>): Promise<T> {
  console.info(`[${name}] загрузка...`);
  try {
    const result = await action();
    console.info(`[${name}] загружено`);
    return result;
  } catch (error) {
    console.error(`[${name}] ошибка загрузки:`, error);
    throw error;
  }
}
