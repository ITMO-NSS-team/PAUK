// Единое типизированное состояние приложения. Заменяет то, что в старом
// GUI было россыпью независимых глобальных переменных (var tab, var
// selected, var LANG — каждая в своём файле, без единой точки правды).
// Здесь один объект AppState и один Store, который его хранит и уведомляет
// подписчиков об изменениях — без Redux/экшенов/редьюсеров, они здесь
// не нужны: логика простая, а вот общий источник правды — обязателен.

// В старом GUI была ещё вкладка 5 "Здоровье БД" — решили её не переносить
// вообще, поэтому в TabId её нет и никогда не будет: не резервируем номер
// под фичу, которую сознательно не строим.
//
// Вкладка "Поиск" (была 4) временно убрана — переезжает в левую панель
// каждой вкладки вместе с фильтрами, когда решится, как именно (см. память
// проекта). Сама логика поиска осталась в features/search/index.ts, просто
// не смонтирована как отдельная вкладка. Числа 1/2/3 не переименовывались
// под новый порядок кнопок в index.html (Авторы/Публикации/Репозитории) —
// после перехода на слаги в URL (core/url.ts) это чисто внутренние id, не
// видны пользователю нигде.
/** Номер вкладки: 1 — авторы, 2 — репозитории, 3 — публикации. */
export type TabId = 1 | 2 | 3;

/**
 * Что сейчас выбрано на карте/в интерфейсе. `null` — ничего не выбрано.
 * Три варианта соответствуют трём типам вещей, которые можно выбрать:
 * узел графа (автор/репозиторий/публикация), ребро (связь между двумя
 * узлами, с весом `w`) или целый департамент (клик по результату поиска —
 * своей "точки" на карте у департамента нет, в отличие от старого GUI с его
 * облаками-халлами).
 */
export type Selection =
  | { kind: "node"; key: string }
  | { kind: "edge"; s: string; t: string; w: number }
  | { kind: "dept"; id: number }
  | null;

/**
 * Какой "экран" сейчас показан — независимо от `tab`. `"menu"` — стартовое
 * меню (языки + выбор вкладки, features/start.ts) визуально полностью
 * перекрывает сайдбар/карту/панель непрозрачным full-screen оверлеем (сам
 * `#app` при этом физически остаётся в раскладке страницы, не схлопывается
 * до нулевых размеров — Sigma конструируется сразу после загрузки данных
 * независимо от `screen`, ей нужны настоящие размеры `#map` в этот момент,
 * см. index.html). `"app"` — обычный интерфейс. Сознательно отдельное поле, а
 * не третье значение `TabId` (вроде `"start" | 1 | 2 | 3`) — `tab` тогда
 * пришлось бы сужать типом почти везде, где он уже используется
 * (map/build.ts, features/tabs/index.ts, features/filters.ts), хотя реальный
 * смысл "какой из трёх графов" при этом не меняется вообще.
 */
export type Screen = "menu" | "app";

/** Всё состояние приложения в одном месте — единственный источник правды. */
export interface AppState {
  /** Показано меню или обычный интерфейс — см. {@link Screen}. */
  screen: Screen;
  /** Активная вкладка сайдбара — какой из трёх графов рисует карта и какой список показан. Осмысленна только при `screen === "app"`. */
  tab: TabId;
  /** Текущий язык интерфейса и данных. */
  lang: "ru" | "en";
  /** Что сейчас выбрано (узел/ребро/департамент) — читается панелью информации, картой и списками вкладок. */
  selection: Selection;
  /**
   * Пороги фильтров рёбер/узлов на карте — применяются в map/build.ts,
   * управляются из features/filters.ts. Значения по умолчанию задаются
   * при создании Store в main.ts, здесь только форма.
   * - `minCoauth` — вкладка "Авторы": скрыть связи соавторства слабее N
   *   совместных публикаций (`coauth_edges.w`).
   * - `minSharedAuthors` — вкладка "Публикации": скрыть связи между
   *   публикациями слабее N общих авторов (`pub_edges.w`). НЕ "число
   *   авторов у одной публикации" — раньше поле было названо
   *   `minPubAuthors`, что описывало не то, что оно реально фильтрует.
   * - `yearMax` — вкладка "Публикации": скрыть публикации (и их рёбра)
   *   позже этого года.
   * - `showNoDeptAuthors`/`showNoDeptPubs` — показывать ли авторов/публикации
   *   без реального департамента (у new_generate/departments.py для них есть
   *   синтетическая запись "Без департамента", см. core/config.ts::NO_DEPT_COLOR).
   *   По умолчанию `true` — сегодняшнее поведение не меняется, пока не выключат явно.
   */
  filters: {
    minCoauth: number;
    minSharedAuthors: number;
    yearMax: number;
    showNoDeptAuthors: boolean;
    showNoDeptPubs: boolean;
  };
}

/**
 * Маленькое типизированное хранилище состояния — паттерн "наблюдатель"
 * (observer): любой код может подписаться на изменения через `subscribe()`
 * и сам решает, что перерисовать. Сознательно без экшенов/редьюсеров —
 * они оправданы, когда логика изменения состояния сложная и её нужно
 * тестировать отдельно от компонентов; здесь состояние маленькое и
 * плоское, лишний слой абстракции только усложнил бы код.
 *
 * @typeParam S - форма хранимого состояния (в приложении это всегда {@link AppState}).
 *
 * @example
 * const store = new Store<AppState>({ tab: 1, lang: "ru", selection: null, filters: {...} });
 *
 * const unsubscribe = store.subscribe((state) => {
 *   console.log("новая вкладка:", state.tab);
 * });
 *
 * store.set({ tab: 2 }); // выведет "новая вкладка: 2"
 * unsubscribe(); // больше не будет получать уведомления
 */
export class Store<S extends object> {
  private state: S;
  // Set, а не массив — подписчик может отписаться (delete) за O(1) и не
  // важен порядок вызова колбэков.
  private listeners = new Set<(state: Readonly<S>) => void>();

  /**
   * @param initial - начальное состояние. Задаётся один раз, при создании
   *   Store (в приложении — единственный раз, в app/main.ts).
   */
  constructor(initial: S) {
    this.state = initial;
  }

  /**
   * Текущее состояние целиком.
   *
   * @returns Состояние как `Readonly<S>` — снаружи менять его поля напрямую
   *   нельзя (TypeScript не даст присвоить `store.get().tab = 2`), менять
   *   можно только через {@link Store.set}.
   */
  get(): Readonly<S> {
    return this.state;
  }

  /**
   * Точечно обновляет состояние (как `setState` в привычных
   * UI-фреймворках): `patch` мержится поверх текущего state через
   * object-spread, а не заменяет его целиком — можно передать только то,
   * что реально меняется, остальные поля остаются как были. После
   * обновления синхронно вызывает всех подписчиков из {@link Store.subscribe}.
   *
   * @param patch - частичный набор полей `S`, которые нужно заменить.
   *
   * @example
   * store.set({ lang: "en" }); // меняет только lang, tab/selection/filters не трогает
   */
  set(patch: Partial<S>): void {
    this.state = { ...this.state, ...patch };
    this.notify();
  }

  /**
   * Оповещает подписчиков без изменения самого состояния — для данных,
   * которые лежат НЕ в `S` (например, detail-карты авторов/репозиториев в
   * `app/main.ts`: они мутируются на месте по той же ссылке, которую уже
   * держат `mountPanel`/`mountReactiveGraph`, и notify() — единственное,
   * что им нужно, чтобы перечитать эту ссылку и перерисоваться под новые
   * данные). Обычный `set({})` дал бы тот же эффект (пустой патч тоже
   * уведомляет слушателей), но `notify()` называет намерение прямо, а не
   * маскирует его под "пустое изменение состояния".
   *
   * @example
   * const authorDetails = new Map<string, AuthorDetail>();
   * mountPanel(store, data, pubDetails, authorDetails, repoDetails); // authorDetails пока пуст
   * // ...позже, когда пришёл authors-detail.json:
   * for (const detail of await loadDetails()) authorDetails.set(detail.key, detail);
   * store.notify(); // уже смонтированная панель перечитывает authorDetails и перерисовывается
   */
  notify(): void {
    // this.state читается ЗАНОВО на каждый вызов колбэка, а не один раз до
    // forEach — если слушатель внутри себя вызовет store.set() (например,
    // map/build.ts::mountReactiveGraph обнуляет устаревший selection при
    // пересборке графа), это меняет this.state и запускает СВОЙ вложенный
    // notify() прямо посреди текущего forEach. Если бы здесь передавался
    // один и тот же снимок всем подписчикам этого раунда, то подписчики,
    // до которых forEach ещё не дошёл (например, features/panels.ts —
    // перерисовывается безусловно, без своего "уже видел это состояние"
    // guard'а, в отличие от features/tabs/index.ts::activateTab), получили
    // бы уже устаревшее значение и перезаписали бы им корректный результат
    // вложенной рассылки. Чтение заново делает каждый последующий вызов в
    // этом же раунде идемпотентным при повторном совпадении состояния.
    this.listeners.forEach((listener) => listener(this.state));
  }

  /**
   * Подписка на изменения состояния. Слушатель вызывается синхронно сразу
   * после каждого {@link Store.set}, с новым (уже обновлённым) состоянием.
   *
   * @param listener - функция, которую нужно вызывать при каждом изменении состояния.
   * @returns Функцию отписки — вызывающий код (обычно `mount()` конкретной
   *   вкладки/фичи) обязан вызвать её при размонтировании, иначе накопится
   *   утечка подписчиков на несуществующий DOM.
   *
   * @example
   * const unsubscribe = store.subscribe((state) => renderPanel(state));
   * // ...позже, при размонтировании фичи:
   * unsubscribe();
   */
  subscribe(listener: (state: Readonly<S>) => void): () => void {
    this.listeners.add(listener);
    return () => this.listeners.delete(listener);
  }
}
